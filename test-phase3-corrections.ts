import { ShopifyService } from './server/shopifyService';
import { subscriptionStore } from './server/subscriptionStore';

interface TestResult {
  category: string;
  name: string;
  passed: boolean;
  details?: string;
  error?: string;
}

const testResults: TestResult[] = [];

function assert(condition: boolean, category: string, name: string, details?: string) {
  if (condition) {
    testResults.push({ category, name, passed: true, details });
    console.log(`[PASS] [${category}] ${name}${details ? ` -> ${details}` : ''}`);
  } else {
    testResults.push({ category, name, passed: false, details, error: 'Assertion failed' });
    console.error(`[FAIL] [${category}] ${name}${details ? ` -> ${details}` : ''}`);
  }
}

async function runCorrectionsTests() {
  console.log('================================================================');
  console.log('LIFE RESET PHASE 3 AUDIT CORRECTIONS TEST SUITE');
  console.log('================================================================\n');

  // =========================================================================
  // 1. MONTH-END BILLING ANCHOR TESTS
  // =========================================================================
  console.log('--- 1. MONTH-END BILLING ANCHOR ---');

  // Test 1A: Non-leap year consecutive cycles (2026): Jan 31 -> Feb 28 -> Mar 31 -> Apr 30 -> May 31
  try {
    const anchor = 31;

    // Cycle 1: Initial order Jan 31, 2026
    const order1Jan31 = '2026-01-31T14:00:00.000Z';
    const c1 = ShopifyService.calculateBillingCyclePeriods(order1Jan31, 72, anchor);
    assert(
      c1.currentPeriodEnd === '2026-02-28T14:00:00.000Z' && c1.billingAnchorDay === 31,
      'MONTH-END ANCHOR',
      'Cycle 1 (Jan 31 -> Feb 28 non-leap)',
      `periodEnd: ${c1.currentPeriodEnd}, anchor: ${c1.billingAnchorDay}`
    );

    // Cycle 2: Renewal order generated by Shopify on Feb 28, 2026
    // CRITICAL: With anchor 31, the period end in March MUST be March 31, NOT March 28!
    const order2Feb28 = '2026-02-28T14:00:00.000Z';
    const c2 = ShopifyService.calculateBillingCyclePeriods(order2Feb28, 72, anchor);
    assert(
      c2.currentPeriodEnd === '2026-03-31T14:00:00.000Z' && c2.billingAnchorDay === 31,
      'MONTH-END ANCHOR',
      'Cycle 2 (Feb 28 order -> March 31 with anchor 31)',
      `periodEnd: ${c2.currentPeriodEnd} (successfully prevented drift to March 28!)`
    );

    // Cycle 3: Renewal order on March 31, 2026
    const order3Mar31 = '2026-03-31T14:00:00.000Z';
    const c3 = ShopifyService.calculateBillingCyclePeriods(order3Mar31, 72, anchor);
    assert(
      c3.currentPeriodEnd === '2026-04-30T14:00:00.000Z' && c3.billingAnchorDay === 31,
      'MONTH-END ANCHOR',
      'Cycle 3 (Mar 31 order -> April 30 clamped)',
      `periodEnd: ${c3.currentPeriodEnd}`
    );

    // Cycle 4: Renewal order on April 30, 2026
    const order4Apr30 = '2026-04-30T14:00:00.000Z';
    const c4 = ShopifyService.calculateBillingCyclePeriods(order4Apr30, 72, anchor);
    assert(
      c4.currentPeriodEnd === '2026-05-31T14:00:00.000Z' && c4.billingAnchorDay === 31,
      'MONTH-END ANCHOR',
      'Cycle 4 (Apr 30 order -> May 31 with anchor 31)',
      `periodEnd: ${c4.currentPeriodEnd}`
    );
  } catch (e: any) {
    assert(false, 'MONTH-END ANCHOR', 'Non-leap year cycles', e.message);
  }

  // Test 1B: Leap year consecutive cycles (2024 / 2028): Jan 31 -> Feb 29 -> Mar 31 -> Apr 30
  try {
    const leapAnchor = 31;

    // Cycle 1: Initial order Jan 31, 2024 (Leap year)
    const leapOrder1 = '2024-01-31T10:00:00.000Z';
    const l1 = ShopifyService.calculateBillingCyclePeriods(leapOrder1, 72, leapAnchor);
    assert(
      l1.currentPeriodEnd === '2024-02-29T10:00:00.000Z',
      'MONTH-END ANCHOR',
      'Cycle 1 Leap (Jan 31 -> Feb 29 leap day)',
      `periodEnd: ${l1.currentPeriodEnd}`
    );

    // Cycle 2: Renewal order Feb 29, 2024
    const leapOrder2 = '2024-02-29T10:00:00.000Z';
    const l2 = ShopifyService.calculateBillingCyclePeriods(leapOrder2, 72, leapAnchor);
    assert(
      l2.currentPeriodEnd === '2024-03-31T10:00:00.000Z',
      'MONTH-END ANCHOR',
      'Cycle 2 Leap (Feb 29 -> Mar 31 with anchor 31)',
      `periodEnd: ${l2.currentPeriodEnd}`
    );

    // Cycle 3: Renewal order Mar 31, 2024
    const leapOrder3 = '2024-03-31T10:00:00.000Z';
    const l3 = ShopifyService.calculateBillingCyclePeriods(leapOrder3, 72, leapAnchor);
    assert(
      l3.currentPeriodEnd === '2024-04-30T10:00:00.000Z',
      'MONTH-END ANCHOR',
      'Cycle 3 Leap (Mar 31 -> Apr 30 clamped)',
      `periodEnd: ${l3.currentPeriodEnd}`
    );
  } catch (e: any) {
    assert(false, 'MONTH-END ANCHOR', 'Leap year cycles', e.message);
  }

  // Test 1C: Grace period gap verification
  try {
    // When Feb 28 order is processed with anchor 31:
    const febPeriods = ShopifyService.calculateBillingCyclePeriods('2026-02-28T12:00:00.000Z', 72, 31);
    const mar31BillTime = new Date('2026-03-31T12:00:00.000Z').getTime();
    const periodEndMs = new Date(febPeriods.currentPeriodEnd).getTime();
    const graceEndMs = new Date(febPeriods.gracePeriodEnd).getTime();

    // Verify currentPeriodEnd matches Shopify's billing date (March 31)
    const exactMatch = periodEndMs === mar31BillTime;
    // Verify grace period extends to April 3 (72 hours after March 31)
    const remainingGraceHours = (graceEndMs - mar31BillTime) / (3600 * 1000);

    assert(
      exactMatch && remainingGraceHours === 72,
      'MONTH-END ANCHOR',
      'Grace period buffer across February to March',
      `currentPeriodEnd is ${febPeriods.currentPeriodEnd}, graceEnd is ${febPeriods.gracePeriodEnd} (72h buffer remaining when Mar 31 bills)`
    );
  } catch (e: any) {
    assert(false, 'MONTH-END ANCHOR', 'Grace period gap analysis', e.message);
  }

  // Test 1D: Auto-derivation and Store Persistence
  try {
    const testUid = 'test-anchor-uid-' + Date.now();
    // Simulate initial order on Jan 31
    const initialOrder = {
      id: 'gid://shopify/Order/88880001',
      name: '#1001',
      displayFinancialStatus: 'PAID',
      processedAt: '2026-01-31T15:00:00.000Z',
      createdAt: '2026-01-31T15:00:00.000Z',
      cancelledAt: null,
      disputes: [],
      totalRefundedSet: { shopMoney: { amount: '0.00' } },
      totalPriceSet: { shopMoney: { amount: '9.99' } },
    };

    // Evaluate lifecycle without pre-existing anchor (auto-derives anchor 31 from order date)
    const lifecycle1 = ShopifyService.evaluateOrderSubscriptionLifecycle(initialOrder);
    assert(
      lifecycle1.billingAnchorDay === 31,
      'MONTH-END ANCHOR',
      'Auto-derive anchor day from initial order processedAt',
      `derived anchor: ${lifecycle1.billingAnchorDay}`
    );

    // Save to store
    subscriptionStore.setStatus(testUid, 'active', {
      email: 'anchor@example.com',
      billingAnchorDay: lifecycle1.billingAnchorDay,
      currentPeriodEnd: lifecycle1.currentPeriodEnd,
      gracePeriodEnd: lifecycle1.gracePeriodEnd,
      lastPaidOrderId: initialOrder.id,
    });

    const stored = subscriptionStore.getByUserId(testUid);
    assert(
      stored?.billingAnchorDay === 31,
      'MONTH-END ANCHOR',
      'Persist billingAnchorDay in store',
      `stored anchor: ${stored?.billingAnchorDay}`
    );

    // Clean up test key
    (subscriptionStore as any).records.delete(testUid);
  } catch (e: any) {
    assert(false, 'MONTH-END ANCHOR', 'Store persistence', e.message);
  }

  // =========================================================================
  // 2. CHARGEBACK DETECTION TESTS
  // =========================================================================
  console.log('\n--- 2. CHARGEBACK DETECTION ---');

  // Test 2A: Confirmed chargeback: initiatedAs === 'CHARGEBACK' && status === 'ACCEPTED'
  try {
    const orderAccepted = {
      id: 'gid://shopify/Order/88880002',
      displayFinancialStatus: 'PAID',
      processedAt: '2026-01-15T00:00:00Z',
      cancelledAt: null,
      disputes: [
        { id: 'gid://shopify/Dispute/1', initiatedAs: 'CHARGEBACK', status: 'ACCEPTED' },
      ],
      totalRefundedSet: { shopMoney: { amount: '0.00' } },
      totalPriceSet: { shopMoney: { amount: '9.99' } },
    };
    const res = ShopifyService.evaluateOrderSubscriptionLifecycle(orderAccepted);
    assert(
      res.eligible === false && res.hasActiveAccess === false && res.status === 'cancelled',
      'CHARGEBACK DETECTION',
      'Chargeback with status ACCEPTED',
      `eligible=${res.eligible}, access=${res.hasActiveAccess}, reason="${res.reason}"`
    );
  } catch (e: any) {
    assert(false, 'CHARGEBACK DETECTION', 'Chargeback ACCEPTED', e.message);
  }

  // Test 2B: Confirmed chargeback: initiatedAs === 'CHARGEBACK' && status === 'LOST'
  try {
    const orderLost = {
      id: 'gid://shopify/Order/88880003',
      displayFinancialStatus: 'PAID',
      processedAt: '2026-01-15T00:00:00Z',
      cancelledAt: null,
      disputes: [
        { id: 'gid://shopify/Dispute/2', initiatedAs: 'CHARGEBACK', status: 'LOST' },
      ],
      totalRefundedSet: { shopMoney: { amount: '0.00' } },
      totalPriceSet: { shopMoney: { amount: '9.99' } },
    };
    const res = ShopifyService.evaluateOrderSubscriptionLifecycle(orderLost);
    assert(
      res.eligible === false && res.hasActiveAccess === false && res.status === 'cancelled',
      'CHARGEBACK DETECTION',
      'Chargeback with status LOST',
      `eligible=${res.eligible}, access=${res.hasActiveAccess}, reason="${res.reason}"`
    );
  } catch (e: any) {
    assert(false, 'CHARGEBACK DETECTION', 'Chargeback LOST', e.message);
  }

  // Test 2C: Non-confirmed dispute: initiatedAs === 'CHARGEBACK' && status === 'NEEDS_RESPONSE'
  try {
    const orderOpen = {
      id: 'gid://shopify/Order/88880004',
      displayFinancialStatus: 'PAID',
      processedAt: '2026-01-15T00:00:00Z',
      cancelledAt: null,
      disputes: [
        { id: 'gid://shopify/Dispute/3', initiatedAs: 'CHARGEBACK', status: 'NEEDS_RESPONSE' },
      ],
      totalRefundedSet: { shopMoney: { amount: '0.00' } },
      totalPriceSet: { shopMoney: { amount: '9.99' } },
    };
    // Evaluated within paid period
    const refTime = new Date('2026-01-20T00:00:00Z').getTime();
    const res = ShopifyService.evaluateOrderSubscriptionLifecycle(orderOpen, refTime);
    assert(
      res.eligible === true && res.hasActiveAccess === true,
      'CHARGEBACK DETECTION',
      'Open dispute with status NEEDS_RESPONSE (not yet lost/accepted)',
      `eligible=${res.eligible}, access=${res.hasActiveAccess}`
    );
  } catch (e: any) {
    assert(false, 'CHARGEBACK DETECTION', 'Open dispute NEEDS_RESPONSE', e.message);
  }

  // Test 2D: Dispute won by merchant: status === 'WON'
  try {
    const orderWon = {
      id: 'gid://shopify/Order/88880005',
      displayFinancialStatus: 'PAID',
      processedAt: '2026-01-15T00:00:00Z',
      cancelledAt: null,
      disputes: [
        { id: 'gid://shopify/Dispute/4', initiatedAs: 'CHARGEBACK', status: 'WON' },
      ],
      totalRefundedSet: { shopMoney: { amount: '0.00' } },
      totalPriceSet: { shopMoney: { amount: '9.99' } },
    };
    const refTime = new Date('2026-01-20T00:00:00Z').getTime();
    const res = ShopifyService.evaluateOrderSubscriptionLifecycle(orderWon, refTime);
    assert(
      res.eligible === true && res.hasActiveAccess === true,
      'CHARGEBACK DETECTION',
      'Dispute won by merchant (WON)',
      `eligible=${res.eligible}, access=${res.hasActiveAccess}`
    );
  } catch (e: any) {
    assert(false, 'CHARGEBACK DETECTION', 'Dispute WON', e.message);
  }

  // Test 2E: Inquiry phase: initiatedAs === 'INQUIRY' (not a chargeback)
  try {
    const orderInquiry = {
      id: 'gid://shopify/Order/88880006',
      displayFinancialStatus: 'PAID',
      processedAt: '2026-01-15T00:00:00Z',
      cancelledAt: null,
      disputes: [
        { id: 'gid://shopify/Dispute/5', initiatedAs: 'INQUIRY', status: 'NEEDS_RESPONSE' },
      ],
      totalRefundedSet: { shopMoney: { amount: '0.00' } },
      totalPriceSet: { shopMoney: { amount: '9.99' } },
    };
    const refTime = new Date('2026-01-20T00:00:00Z').getTime();
    const res = ShopifyService.evaluateOrderSubscriptionLifecycle(orderInquiry, refTime);
    assert(
      res.eligible === true && res.hasActiveAccess === true,
      'CHARGEBACK DETECTION',
      'Inquiry phase (initiatedAs === INQUIRY)',
      `eligible=${res.eligible}, access=${res.hasActiveAccess}`
    );
  } catch (e: any) {
    assert(false, 'CHARGEBACK DETECTION', 'Inquiry phase', e.message);
  }

  // Test 2F: Do not classify cancelledAt alone as a chargeback
  try {
    const cancelledOrder = {
      id: 'gid://shopify/Order/88880007',
      displayFinancialStatus: 'PAID',
      processedAt: '2026-01-15T00:00:00Z',
      cancelledAt: '2026-01-16T00:00:00Z',
      cancelReason: 'CUSTOMER',
      disputes: [],
      totalRefundedSet: { shopMoney: { amount: '0.00' } },
      totalPriceSet: { shopMoney: { amount: '9.99' } },
    };
    const res = ShopifyService.evaluateOrderSubscriptionLifecycle(cancelledOrder);
    assert(
      res.reason === 'Order was cancelled or voided.' && !res.reason.includes('chargeback'),
      'CHARGEBACK DETECTION',
      'Ordinary cancellation has distinct reason (not chargeback)',
      `reason="${res.reason}"`
    );
  } catch (e: any) {
    assert(false, 'CHARGEBACK DETECTION', 'Ordinary cancellation distinction', e.message);
  }

  // =========================================================================
  // 3. CURSOR-BASED PAGINATION TESTS
  // =========================================================================
  console.log('\n--- 3. ORDER CURSOR-BASED PAGINATION ---');

  // Test 3A: Cursor pagination retrieves order across multiple pages
  try {
    const numericCustomerId = '99991111';
    const expectedSellingPlanId = 'gid://shopify/SellingPlan/692445053203';

    // Mock queryAdminGraphQL to simulate 2 pages:
    // Page 1: 3 non-subscription orders, hasNextPage = true, endCursor = 'cursor_page_1'
    // Page 2: 1 subscription order matching customer & plan, hasNextPage = false
    const originalQuery = ShopifyService.queryAdminGraphQL;
    const originalGetCust = (ShopifyService as any).getCustomerIdForOrder;

    let apiCallsCount = 0;
    const pageCursorsReceived: (string | null | undefined)[] = [];

    (ShopifyService as any).queryAdminGraphQL = async (query: string, vars: any) => {
      apiCallsCount++;
      pageCursorsReceived.push(vars?.after);

      if (!vars?.after) {
        // Page 1
        return {
          orders: {
            pageInfo: {
              hasNextPage: true,
              endCursor: 'cursor_page_1',
            },
            edges: [
              {
                cursor: 'cursor_1',
                node: {
                  id: 'gid://shopify/Order/page1_order1',
                  name: '#901',
                  displayFinancialStatus: 'PAID',
                  cancelledAt: null,
                  createdAt: '2026-11-01T00:00:00Z',
                  processedAt: '2026-11-01T00:00:00Z',
                  disputes: [],
                  lineItems: { edges: [{ node: { sellingPlan: null } }] }, // no selling plan
                },
              },
              {
                cursor: 'cursor_2',
                node: {
                  id: 'gid://shopify/Order/page1_order2',
                  name: '#902',
                  displayFinancialStatus: 'PAID',
                  cancelledAt: null,
                  createdAt: '2026-10-15T00:00:00Z',
                  processedAt: '2026-10-15T00:00:00Z',
                  disputes: [],
                  lineItems: { edges: [{ node: { sellingPlan: { sellingPlanId: 'other-plan' } } }] },
                },
              },
            ],
          },
        };
      } else if (vars.after === 'cursor_page_1') {
        // Page 2
        return {
          orders: {
            pageInfo: {
              hasNextPage: false,
              endCursor: 'cursor_page_2',
            },
            edges: [
              {
                cursor: 'cursor_3',
                node: {
                  id: 'gid://shopify/Order/page2_sub_order',
                  name: '#903',
                  displayFinancialStatus: 'PAID',
                  cancelledAt: null,
                  createdAt: '2026-10-01T12:00:00Z',
                  processedAt: '2026-10-01T12:00:00Z',
                  disputes: [],
                  totalRefundedSet: { shopMoney: { amount: '0.00' } },
                  totalPriceSet: { shopMoney: { amount: '9.99' } },
                  lineItems: {
                    edges: [
                      {
                        node: {
                          sellingPlan: {
                            sellingPlanId: expectedSellingPlanId,
                            name: 'Monthly Life Reset',
                          },
                        },
                      },
                    ],
                  },
                },
              },
            ],
          },
        };
      }
      return { orders: { pageInfo: { hasNextPage: false, endCursor: null }, edges: [] } };
    };

    (ShopifyService as any).getCustomerIdForOrder = async (orderId: string) => {
      return `gid://shopify/Customer/${numericCustomerId}`;
    };

    const res = await ShopifyService.verifyCustomerRecurringOrders({
      shopifyCustomerId: numericCustomerId,
      expectedSellingPlanId,
      billingAnchorDay: 1,
    });

    // Restore original functions
    (ShopifyService as any).queryAdminGraphQL = originalQuery;
    (ShopifyService as any).getCustomerIdForOrder = originalGetCust;

    const paginationSuccess =
      res.verified === true &&
      res.order?.id === 'gid://shopify/Order/page2_sub_order' &&
      apiCallsCount === 2 &&
      (!pageCursorsReceived[0]) &&
      pageCursorsReceived[1] === 'cursor_page_1';

    assert(
      paginationSuccess,
      'PAGINATION',
      'Retrieves qualifying order across multiple pages using cursor',
      `found order on page 2 (calls: ${apiCallsCount}, cursors: ${JSON.stringify(pageCursorsReceived)})`
    );
  } catch (e: any) {
    assert(false, 'PAGINATION', 'Multi-page cursor traversal', e.message);
  }

  // Test 3B: Early exit stops on page 1 when latest qualifying order is found
  try {
    const numericCustomerId = '99992222';
    const expectedSellingPlanId = 'gid://shopify/SellingPlan/692445053203';

    const originalQuery = ShopifyService.queryAdminGraphQL;
    const originalGetCust = (ShopifyService as any).getCustomerIdForOrder;

    let apiCallsCount = 0;

    (ShopifyService as any).queryAdminGraphQL = async (query: string, vars: any) => {
      apiCallsCount++;
      return {
        orders: {
          pageInfo: {
            hasNextPage: true, // Has another page, but we must NOT fetch it!
            endCursor: 'cursor_more_pages',
          },
          edges: [
            {
              cursor: 'cursor_first',
              node: {
                id: 'gid://shopify/Order/page1_immediate_match',
                name: '#1001',
                displayFinancialStatus: 'PAID',
                cancelledAt: null,
                createdAt: new Date().toISOString(),
                processedAt: new Date().toISOString(),
                disputes: [],
                totalRefundedSet: { shopMoney: { amount: '0.00' } },
                totalPriceSet: { shopMoney: { amount: '9.99' } },
                lineItems: {
                  edges: [
                    {
                      node: {
                        sellingPlan: {
                          sellingPlanId: expectedSellingPlanId,
                        },
                      },
                    },
                  ],
                },
              },
            },
          ],
        },
      };
    };

    (ShopifyService as any).getCustomerIdForOrder = async (orderId: string) => {
      return `gid://shopify/Customer/${numericCustomerId}`;
    };

    const res = await ShopifyService.verifyCustomerRecurringOrders({
      shopifyCustomerId: numericCustomerId,
      expectedSellingPlanId,
    });

    // Restore
    (ShopifyService as any).queryAdminGraphQL = originalQuery;
    (ShopifyService as any).getCustomerIdForOrder = originalGetCust;

    const earlyExitSuccess =
      res.verified === true &&
      res.order?.id === 'gid://shopify/Order/page1_immediate_match' &&
      apiCallsCount === 1;

    assert(
      earlyExitSuccess,
      'PAGINATION',
      'Early exit: stops immediately when qualifying order found on page 1 without fetching next page',
      `calls: ${apiCallsCount}`
    );
  } catch (e: any) {
    assert(false, 'PAGINATION', 'Early exit', e.message);
  }

  // =========================================================================
  // SUMMARY
  // =========================================================================
  console.log('\n================================================================');
  const allPassed = testResults.every(r => r.passed);
  console.log(`TOTAL AUDIT TESTS: ${testResults.length} | PASSED: ${testResults.filter(r => r.passed).length} | FAILED: ${testResults.filter(r => !r.passed).length}`);
  console.log(`OVERALL STATUS: ${allPassed ? 'ALL CORRECTIONS VERIFIED & PASSED' : 'FAILURES DETECTED'}`);
  console.log('================================================================\n');

  if (!allPassed) {
    process.exit(1);
  }
}

runCorrectionsTests().catch(err => {
  console.error('Test execution failed:', err);
  process.exit(1);
});
